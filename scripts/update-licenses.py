#!/usr/bin/env python3
"""Collect locked Cargo dependency notices; --check detects stale generated output."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    cargo = shutil.which('cargo') or str(Path.home() / '.cargo/bin/cargo')
    metadata = json.loads(subprocess.check_output(
        [cargo, 'metadata', '--locked', '--offline', '--format-version', '1'], cwd=root))
    supplements = root / 'licenses/upstream'
    provenance = json.loads((supplements / 'sources.json').read_text())
    for relative, record in provenance.items():
        content = (supplements / relative).read_bytes()
        if hashlib.sha256(content).hexdigest() != record['sha256']:
            raise SystemExit(f'Upstream license hash mismatch: {relative}')
    lock_hash = hashlib.sha256((root / 'Cargo.lock').read_bytes()).hexdigest()
    text = ['# Third-party notices', '',
            'Generated by `python3 scripts/update-licenses.py` from the locked Cargo package archives.',
            'Includes direct, transitive, build and target-conditional packages; this does not mean every package or feature is in every binary.',
            'Original license texts and copyright notices follow unchanged. Cargo license expressions are declarations, not a complete legal audit.',
            'Where alternatives permit, use the MIT option, otherwise Apache-2.0; retain additional required Unicode/Zlib terms. Keeping alternative texts does not elect copyleft terms.',
            'The MCP SDK upstream license contains its own Apache/MIT transition terms, which remain applicable regardless of its Cargo label.',
            'Native bundled components and Rust runtime/platform notices also require review for each binary release.',
            f'Cargo.lock SHA-256: `{lock_hash}`', '']
    inventory = []
    for package in sorted(metadata['packages'], key=lambda p: (p['name'], p['version'])):
        if package['source'] is None:
            continue
        package_root = Path(package['manifest_path']).parent
        files = sorted(f for f in package_root.rglob('*') if f.is_file()
                       and any(t in f.name.lower() for t in ['license', 'notice', 'copying', 'copyright']))
        package_id = package['name'] + '-' + package['version']
        extra = [(supplements / rel, record['url']) for rel, record in sorted(provenance.items())
                 if rel.startswith(package_id + '/')]
        if not files and not extra:
            raise SystemExit(f'Missing license text for {package_id}; inspect the exact upstream revision before adding a supplement.')
        text += [f"## {package['name']} {package['version']}", '',
                 f"Declared license: `{package['license']}`", '',
                 f"Package: https://crates.io/crates/{package['name']}/{package['version']}", '']
        notices = []
        for file, origin in [(f, f'Cargo archive: {f.relative_to(package_root)}') for f in files] + extra:
            data = file.read_bytes()
            notices.append({'origin': origin, 'sha256': hashlib.sha256(data).hexdigest()})
            text += [f'### {origin}', '', '````text', data.decode('utf-8').rstrip('\n'), '````', '']
        inventory.append({'name': package['name'], 'version': package['version'],
                          'license': package['license'], 'repository': package.get('repository'), 'notices': notices})
    outputs = {
        root / 'THIRD_PARTY_NOTICES.md': '\n'.join(text) + '\n',
        root / 'licenses/inventory.json': json.dumps({'cargo_lock_sha256': lock_hash, 'packages': inventory}, indent=2, sort_keys=True) + '\n',
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                raise SystemExit(f'Stale or missing {path.name}; run python3 scripts/update-licenses.py')
        else:
            path.write_text(content)
    print(f'{"Checked" if args.check else "Collected"} notices for {len(inventory)} locked Cargo dependencies.')


if __name__ == '__main__':
    main()
